#!/usr/bin/env python3
"""Write the KDE colour schemes PaftaPaper and PaftaNight from palette.toml.

    python3 -I plasma/colors.py      -> home/.local/share/color-schemes/
"""
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAL = tomllib.loads((ROOT / "palette.toml").read_text())
OUT = ROOT / "home/.local/share/color-schemes"


def c(h):
    return ",".join(str(int(h[i:i + 2], 16)) for i in (1, 3, 5))


def mixh(a, b, t):
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(pa, pb))


def group(p, bg, alt, fg=None, inactive=None):
    fg = fg or p["ink"]
    return {
        "BackgroundNormal": bg, "BackgroundAlternate": alt,
        "DecorationFocus": p["blue"], "DecorationHover": mixh(p["blue"], bg, 0.35),
        "ForegroundNormal": fg, "ForegroundInactive": inactive or p["ink3"],
        "ForegroundActive": p["magenta"], "ForegroundLink": p["blue"], "ForegroundVisited": p["magenta"],
        "ForegroundNegative": p["red"], "ForegroundNeutral": p["ochre"], "ForegroundPositive": p["green"],
    }


def scheme(name, title, p, note):
    n = PAL["night"]
    sel_fg = PAL["paper"]["view"]
    sections = {
        "Colors:Window": group(p, p["window"], p["header"]),
        "Colors:View": group(p, p["view"], mixh(p["view"], p["window"], 0.5)),
        "Colors:Button": group(p, mixh(p["view"], p["window"], 0.3), p["header"]),
        "Colors:Header": group(p, p["header"], p["raised"]),
        "Colors:Header][Inactive": group(p, p["header"], p["raised"], fg=p["ink2"], inactive=p["ink3"]),
        "Colors:Tooltip": group(p, p["header"], p["raised"]),
        "Colors:Selection": {**group(p, PAL["paper"]["blue"], mixh(PAL["paper"]["blue"], sel_fg, 0.25), fg=sel_fg,
                                     inactive=mixh(sel_fg, PAL["paper"]["blue"], 0.3)),
                             "ForegroundLink": sel_fg, "ForegroundActive": sel_fg, "ForegroundVisited": sel_fg},
        "Colors:Complementary": group(n, n["header"], n["window"]),
    }
    out = [f"# {title}: {note}", "# Generated by plasma/colors.py from palette.toml; edit the palette, not this file.",
           "[ColorEffects:Disabled]", "Color=56,56,56", "ColorAmount=0", "ColorEffect=0", "ContrastAmount=0.65",
           "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", "",
           "[ColorEffects:Inactive]", "ChangeSelectionColor=true", "Color=112,111,110", "ColorAmount=0.025",
           "ColorEffect=2", "ContrastAmount=0.1", "ContrastEffect=2", "Enable=false", "IntensityAmount=0",
           "IntensityEffect=0", ""]
    for sec, kv in sections.items():
        out.append(f"[{sec}]")
        out += [f"{k}={c(v)}" for k, v in sorted(kv.items())]
        out.append("")
    out += ["[General]", f"ColorScheme={name}", f"Name={title}", "shadeSortColumn=true", "",
            "[KDE]", "contrast=4", "",
            "[WM]", f"activeBackground={c(p['header'])}", f"activeBlend={c(p['header'])}",
            f"activeForeground={c(p['ink'])}", f"inactiveBackground={c(p['header'])}",
            f"inactiveBlend={c(p['header'])}", f"inactiveForeground={c(p['ink3'])}", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.colors").write_text("\n".join(out))


scheme("PaftaPaper", "Pafta Paper", PAL["paper"], "the day sheet, ink on map paper")
scheme("PaftaNight", "Pafta Night", PAL["night"], "the chart at night")
print("wrote", *sorted(p.name for p in OUT.iterdir()))
